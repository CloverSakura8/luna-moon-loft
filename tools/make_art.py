def emit_rle(var, im):
    """Mostly-transparent images: per row, a count of runs, then x, length and pixels for each run."""
    im = im.convert('RGBA'); w, h = im.size; px = im.load(); vals = []
    for y in range(h):
        runs = []; x = 0
        while x < w:
            if px[x, y][3] < 128: x += 1; continue
            start = x; run = []
            while x < w and px[x, y][3] >= 128:
                r, g, b, _ = px[x, y]; run.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)); x += 1
            runs.append((start, run))
        vals.append(len(runs))
        for start, run in runs: vals += [start, len(run)] + run
    out.append(f"constexpr int {var}W = {w}, {var}H = {h};")
    out.append(f"const uint16_t {var}[] = {{")
    for i in range(0, len(vals), 20): out.append(" " + ",".join(f"0x{v:04x}" for v in vals[i:i+20]) + ",")
    out.append("};")

