from PIL import Image
D = 'assets/moon-loft/'
KEY = 0x0821
out = ["#pragma once", "// Generated by tools/make_art.py from assets/moon-loft. Do not edit by hand.",
       "// RGB565; 0x0821 marks transparent pixels.", "#include <cstdint>", "#include <M5Unified.h>", "namespace art {", "constexpr uint16_t clear = 0x0821;"]

def emit(var, im, keyed=True):
    im = im.convert('RGBA'); w, h = im.size; vals = []
    for r, g, b, a in im.getdata():
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        if keyed and a < 128: v = KEY
        elif v == KEY: v = 0x0841
        vals.append(v)
    out.append(f"constexpr int {var}W = {w}, {var}H = {h};")
    out.append(f"const uint16_t {var}[] = {{")
    for i in range(0, len(vals), 20): out.append(" " + ",".join(f"0x{v:04x}" for v in vals[i:i+20]) + ",")
    out.append("};")

def load(name, size=None):
    im = Image.open(D + name + '.png').convert('RGBA')
    return im.resize(size, Image.BOX) if size else im

def three_slice(im, width, cap=22):
    """Stretch only the plain middle of a plaque so its corners stay crisp."""
    w, h = im.size; res = Image.new('RGBA', (width, h))
    res.paste(im.crop((0, 0, cap, h)), (0, 0)); res.paste(im.crop((w - cap, 0, w, h)), (width - cap, 0))
    res.paste(im.crop((cap, 0, w - cap, h)).resize((width - 2 * cap, h), Image.NEAREST), (cap, 0))
    return res

