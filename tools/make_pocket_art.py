"""Convert Pocket Luna's art in assets/moon-loft/pocket into src/pocket_art.hpp for the StickS3.
Run:  .buildenv/bin/python tools/make_pocket_art.py   (needs Pillow)"""
from PIL import Image
D = 'assets/moon-loft/pocket/'
KEY = 0x0821
CELL = 120
out = ["#pragma once", "// Generated by tools/make_pocket_art.py. Do not edit by hand.", "// RGB565; 0x0821 marks transparent pixels.",
       "#include <cstdint>", "namespace pet {", "constexpr uint16_t clear = 0x0821;", f"constexpr int cell = {CELL};"]
def emit(var, im, keyed=True):
    im = im.convert('RGBA'); vals = []
    for r, g, b, a in im.getdata():
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        if keyed and a < 128: v = KEY
        elif v == KEY: v = 0x0841
        vals.append(v)
    out.append(f"const uint16_t {var}[] = {{")
    for i in range(0, len(vals), 24): out.append(" " + ",".join(f"0x{v:04x}" for v in vals[i:i+24]) + ",")
    out.append("};")
def cells(name, count, size, prefix):
    sheet = Image.open(D + name + '.png').convert('RGBA'); w = sheet.size[0] // count; h = sheet.size[1]; names = []
    for i in range(count):
        emit(f'{prefix}{i}', sheet.crop((i * w, 0, i * w + w, h)).resize((size, size), Image.BOX)); names.append(f'{prefix}{i}')
    return names
stage_names = []
for i, name in enumerate(('stage1_kitten', 'stage2_starcat', 'stage3_guardian', 'stage4_queen', 'stage5_angel', 'stage6_goddess')):
    stage_names.append(cells(name, 5, CELL, f'stage{i}_'))
react = cells('reactions', 7, CELL, 'react')
idle = cells('idles', 5, CELL, 'idle')
keep = cells('keepsakes', 6, 20, 'keep')
treat = cells('treats', 6, 16, 'treat')
emit('camera', Image.open(D + 'pocket_camera.png').convert('RGBA').resize((CELL, CELL), Image.BOX))
emit('burst', Image.open(D + 'levelup_burst.png').convert('RGBA').resize((135, 135), Image.BOX))
emit('night', Image.open(D + 'pocket_bg_night.png').resize((135, 240), Image.BOX), keyed=False)
emit('sleep', Image.open(D + 'pocket_bg_sleep.png').resize((135, 240), Image.BOX), keyed=False)
emit('party', Image.open(D + 'pocket_bg_party.png').resize((135, 240), Image.BOX), keyed=False)
out.append("const uint16_t* const stages[6][5] = {" + ",".join("{" + ",".join(n) + "}" for n in stage_names) + "};")
for label, names in (('reactions', react), ('idles', idle), ('keepsakes', keep), ('treats', treat)):
    out.append(f"const uint16_t* const {label}[{len(names)}] = {{" + ",".join(names) + "};")
out.append("}  // namespace pet")
open('src/pocket_art.hpp', 'w').write("\n".join(out) + "\n")
print('wrote src/pocket_art.hpp')
